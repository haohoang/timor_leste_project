SELECT
  ACTION_ID,
  FROM_ACCOUNT,
  TO_ACCOUNT,
  FROM_NAME,
  TO_NAME,
  TO_CURRENCY,
  ORG_CURRENCY,
  EX_RATE,
  CREATED_DATE,
  ACTION_STATE,
  SECRET_CODE,
  LOCK_ACTION_ID,
  REFER_ACTION_ID,
  CARRIED_ACCOUNT,
  CARRIED_NAME,
  AREA_RECEIVER,
  ADDRESS,
  PROCESS_CODE,
  LAST_MODIFIED,
  CARRIED_CODE,
  STAFF_CODE,
  STAFF_NAME,
  EXPIRED_DATE,
  AMOUNT,
  ORG_AMOUNT,
  FROM_PHONE,
  TO_PHONE,
  CONTENT,
  RE_CARRIED_ACCOUNT,
  RE_CARRIED_NAME,
  RE_STAFF_CODE,
  RE_STAFF_NAME,
  RE_CARRIED_PHONE,
  CARRIED_PHONE,
  TRANSACTION_ID
FROM
  "TRANS_CASH"
WHERE
  CREATED_DATE BETWEEN TRUNC(SYSDATE - 1)
            AND TRUNC(SYSDATE) - 1/86400;
